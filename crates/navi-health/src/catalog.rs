#[allow(clippy::too_many_arguments)]
const fn food(
    id: &'static str,
    name_en: &'static str,
    name_zh: &'static str,
    kcal: f64,
    protein: f64,
    carbs: f64,
    fat: f64,
    fiber: f64,
    sugars: f64,
    sodium: f64,
    sat_fat: f64,
) -> CatalogFood {
    CatalogFood {
        id,
        name_en,
        name_zh,
        per_100g: Nutrients::new(kcal, protein, carbs, fat).with_extra(ExtraNutrients {
            fiber,
            sugars,
            sodium,
            sat_fat,
        }),
    }
}

/// The record with FoodData Central id `id`.
pub fn by_id(id: &str) -> Option<&'static CatalogFood> {
    CATALOG.iter().find(|food| food.id == id.trim())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_record_is_plausible_and_unique() {
        for (index, food) in CATALOG.iter().enumerate() {
            assert!(food.per_100g.is_valid_per_100g(), "{}", food.id);
            assert!(CATALOG[index + 1..].iter().all(|other| other.id != food.id));
        }
    }

    #[test]
    fn every_record_keeps_measured_extras() {
        for food in CATALOG {
            assert!(
                food.per_100g.extra.is_some(),
                "record {} has no extra values",
                food.id
            );
        }
    }

    #[test]
    fn looks_up_by_id() {
        assert_eq!(
            by_id(" 168878 ").map(|f| f.name_en),
            Some("White rice, cooked")
        );
        assert!(by_id("000").is_none());
    }
}
